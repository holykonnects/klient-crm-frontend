import test from 'node:test';
import assert from 'node:assert/strict';
import ExcelJS from 'exceljs';
import { quotationGeneratedByEmail, refreshQuotationAuthor } from '../src/utils/quotationAuthor.js';
import { quotationMetaForLead } from '../src/utils/quotationLeadOptions.js';
import { quotationSignoffText } from '../api/_lib/quotationSignoff.js';
import { buildQuotationSetWorkbook } from '../api/_lib/quotationSetExport.js';

const owner = { name: 'Lead Owner', email: 'owner@example.com' };
const manual = { preparedBy: 'author@example.com', preparedByEdited: true, leadSourceName: owner.name, leadSourceEmail: owner.email, clientEmail: 'client@example.com' };

test('manual generated-by email survives lead refresh, selection and draft serialization', () => {
  const saved = JSON.parse(JSON.stringify(manual));
  const refreshed = refreshQuotationAuthor(saved, { name: 'New Owner', email: 'new-owner@example.com' });
  assert.equal(quotationGeneratedByEmail(refreshed), 'author@example.com');
  assert.equal(refreshed.clientEmail, 'client@example.com');
  const selected = quotationMetaForLead({ value: 'Client', email: 'customer@example.com', leadSourceEmail: owner.email }, saved);
  assert.equal(selected.preparedBy, manual.preparedBy);
  assert.equal(selected.clientEmail, 'customer@example.com');
  assert.equal(quotationGeneratedByEmail({ preparedBy: 'old-edit@example.com', leadSourceEmail: owner.email }), 'old-edit@example.com');
});

test('unedited generated-by values follow lead-owner refresh and explicit clearing is respected', () => {
  const defaultMeta = { preparedBy: owner.email, leadSourceEmail: owner.email };
  assert.equal(quotationGeneratedByEmail(refreshQuotationAuthor(defaultMeta, { email: 'new-owner@example.com' })), 'new-owner@example.com');
  assert.equal(quotationGeneratedByEmail({ ...manual, preparedBy: '' }), '');
  assert.equal(quotationGeneratedByEmail({ leadSourceEmail: owner.email }), owner.email);
});

test('PDF signoff uses the manual author without changing banking or client email', () => {
  const source = 'Bank account details\nBest Regards,\nOld Owner\nold@example.com';
  const text = quotationSignoffText(source, manual);
  assert.equal(text, 'Bank account details\nWarm Regards,\nLead Owner\nauthor@example.com');
  assert.equal(manual.clientEmail, 'client@example.com');
});

test('Excel header and footer use the manual generated-by email, not the lead email', async () => {
  const output = await buildQuotationSetWorkbook({ meta: manual, setQuotation: { sets: [{ title: 'Review', items: [{ item: 'Equipment', qty: 1, rate: 100 }] }] } });
  const workbook = new ExcelJS.Workbook();
  await workbook.xlsx.load(output.buffer);
  const sheet = workbook.getWorksheet('Quotation');
  assert.equal(sheet.getRow(5).getCell(4).value, manual.preparedBy);
  assert.equal(sheet.getRow(6).getCell(4).value, manual.clientEmail);
  let footer;
  sheet.eachRow(row => { if (row.getCell(1).value === 'Quotation Generated By') footer = row; });
  assert.equal(footer.getCell(2).value, manual.preparedBy);
});
